"""Built-in practical coding challenges for DGM fitness evaluation."""

from dgm.models import Challenge


def get_builtin_challenges() -> list[Challenge]:
    """Return the 8 built-in practical challenges."""
    return [
        Challenge(
            id="csv_parse",
            name="CSV Parse",
            description="Implement parse_csv(text: str) -> list[dict]. Parse a CSV string (first line is headers) into a list of dicts.",
            function_name="parse_csv",
            test_cases=[
                (("name,age\nAlice,30\nBob,25",), [{"name": "Alice", "age": "30"}, {"name": "Bob", "age": "25"}]),
                (("id,value\n1,hello\n2,world",), [{"id": "1", "value": "hello"}, {"id": "2", "value": "world"}]),
                (("x\n1\n2\n3",), [{"x": "1"}, {"x": "2"}, {"x": "3"}]),
                (("a,b,c\n1,2,3",), [{"a": "1", "b": "2", "c": "3"}]),
                (("",), []),
            ],
            difficulty="easy",
        ),
        Challenge(
            id="json_flatten",
            name="JSON Flatten",
            description='Implement flatten_json(obj: dict) -> dict. Flatten a nested dict using dot notation. E.g. {"a": {"b": 1}} -> {"a.b": 1}. Lists should use index: {"a": [1,2]} -> {"a.0": 1, "a.1": 2}.',
            function_name="flatten_json",
            test_cases=[
                (({"a": 1, "b": 2},), {"a": 1, "b": 2}),
                (({"a": {"b": 1}},), {"a.b": 1}),
                (({"a": {"b": {"c": 3}}},), {"a.b.c": 3}),
                (({"x": [1, 2, 3]},), {"x.0": 1, "x.1": 2, "x.2": 3}),
                (({"a": {"b": [1, 2]}, "c": 3},), {"a.b.0": 1, "a.b.1": 2, "c": 3}),
                (({},), {}),
            ],
            difficulty="medium",
        ),
        Challenge(
            id="rle_compress",
            name="RLE Compress",
            description='Implement rle_encode(s: str) -> str. Run-length encoding: "aaabbc" -> "a3b2c1".',
            function_name="rle_encode",
            test_cases=[
                (("aaabbc",), "a3b2c1"),
                (("a",), "a1"),
                (("",), ""),
                (("aaa",), "a3"),
                (("abcd",), "a1b1c1d1"),
                (("aaAAaa",), "a2A2a2"),
            ],
            difficulty="easy",
        ),
        Challenge(
            id="date_parse",
            name="Date Parse",
            description='Implement parse_date(s: str) -> str. Parse dates in formats "YYYY/MM/DD", "DD-MM-YYYY", "Month DD, YYYY" and return ISO format "YYYY-MM-DD". Return "" for invalid dates.',
            function_name="parse_date",
            test_cases=[
                (("2024/01/15",), "2024-01-15"),
                (("15-01-2024",), "2024-01-15"),
                (("January 15, 2024",), "2024-01-15"),
                (("March 1, 2023",), "2023-03-01"),
                (("2023/12/31",), "2023-12-31"),
                (("invalid",), ""),
                (("31-12-2023",), "2023-12-31"),
            ],
            difficulty="medium",
        ),
        Challenge(
            id="url_parse",
            name="URL Parse",
            description='Implement parse_url(url: str) -> dict. Parse URL into {"scheme": str, "host": str, "path": str, "query": dict}. Query params as key-value dict.',
            function_name="parse_url",
            test_cases=[
                (("https://example.com/path?a=1&b=2",), {"scheme": "https", "host": "example.com", "path": "/path", "query": {"a": "1", "b": "2"}}),
                (("http://test.org",), {"scheme": "http", "host": "test.org", "path": "", "query": {}}),
                (("https://x.com/a/b/c",), {"scheme": "https", "host": "x.com", "path": "/a/b/c", "query": {}}),
                (("http://h.com?key=val",), {"scheme": "http", "host": "h.com", "path": "", "query": {"key": "val"}}),
                (("https://a.com/p?x=1&x=2",), {"scheme": "https", "host": "a.com", "path": "/p", "query": {"x": "2"}}),
            ],
            difficulty="medium",
        ),
        Challenge(
            id="bracket_balance",
            name="Bracket Balance",
            description='Implement is_balanced(s: str) -> bool. Check if brackets ()[]{}  in the string are properly balanced and nested.',
            function_name="is_balanced",
            test_cases=[
                (("([]{})",), True),
                (("([)]",), False),
                (("",), True),
                (("((()))",), True),
                (("{[}]",), False),
                (("hello (world) [test]",), True),
                (("({[",), False),
                (("a(b[c{d}e]f)g",), True),
            ],
            difficulty="easy",
        ),
        Challenge(
            id="markdown_strip",
            name="Markdown Strip",
            description='Implement strip_markdown(text: str) -> str. Remove markdown formatting: **bold**, *italic*, `code`, # headers, - list items, [text](url) -> text. Preserve content.',
            function_name="strip_markdown",
            test_cases=[
                (("**bold**",), "bold"),
                (("*italic*",), "italic"),
                (("`code`",), "code"),
                (("# Header",), "Header"),
                (("- item",), "item"),
                (("[link](http://x.com)",), "link"),
                (("Hello **world** and *test*",), "Hello world and test"),
                (("## Sub header",), "Sub header"),
            ],
            difficulty="hard",
        ),
        Challenge(
            id="num_to_kanji",
            name="Number to Kanji",
            description='Implement to_kanji(n: int) -> str. Convert integer to Japanese kanji numerals. 0->"零", 1->"一", 10->"十", 11->"十一", 20->"二十", 100->"百", 1000->"千", 10000->"一万". Support 0-99999.',
            function_name="to_kanji",
            test_cases=[
                ((0,), "零"),
                ((1,), "一"),
                ((10,), "十"),
                ((11,), "十一"),
                ((20,), "二十"),
                ((100,), "百"),
                ((255,), "二百五十五"),
                ((1000,), "千"),
                ((10000,), "一万"),
                ((12345,), "一万二千三百四十五"),
            ],
            difficulty="hard",
        ),
    ]
