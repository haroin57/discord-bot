_DIGEST_MAX_SOURCES = 50


def build_evidence_digest(state, *, max_chars: int = 24000) -> str:
    """searcher 要約 + 機械収集ソース一覧を、MAGI 各段に渡す共通の「証拠ベース」に整形。

    トークン暴走を避けるため全体を ``max_chars`` で有界化する（ソース一覧は優先的に残す）。
    """
    head: list[str] = ["# 証拠ベース（出典一覧。本文の [S#] はこれに対応）"]
    if state.sources:
        # ソース一覧にも上限を置く。無制限だと大量収集時に fixed 部だけで
        # max_chars を食い潰し、肝心の searcher 要約 budget が 0 になる。
        refs = list(state.sources.values())
        for ref in refs[:_DIGEST_MAX_SOURCES]:
            title = ref.title or ref.url
            head.append(f"[{ref.sid}] {title} — {ref.url}")
        if len(refs) > _DIGEST_MAX_SOURCES:
            head.append(f"…（他 {len(refs) - _DIGEST_MAX_SOURCES} 件のソースを省略）")
    else:
        head.append("(機械収集ソースなし)")
    head.append("")
    head.append("# サーチャーが集めた事実要約")
    fixed = "\n".join(head)
    budget = max(0, max_chars - len(fixed))
    body: list[str] = []
    for i, res in enumerate(state.results, 1):
        if not getattr(res, "ok", False) or not res.summary_md.strip():
            continue
        chunk = f"## サブ質問 {i}: {res.subq}\n{res.summary_md.strip()}\n"
        if budget - len(chunk) < 0:
            body.append("…（以降は文字数上限のため省略）")
            break
        body.append(chunk)
        budget -= len(chunk)
    return fixed + "\n" + "\n".join(body)


